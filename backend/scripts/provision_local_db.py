"""Create FinPilot's isolated local databases and roles on an existing PostgreSQL server.

Run it yourself, in your own terminal. psql asks for the administrator password directly, so this
script never sees it. New role passwords are generated here, sent to the server only as SCRAM
verifiers, written only to backend/.env, and never printed.

    uv run python -m scripts.provision_local_db --print-sql     # review, connects to nothing
    uv run python -m scripts.provision_local_db                 # apply

It only creates. If any name already exists, or backend/.env exists, it stops without changing
anything. It never drops, alters, or inspects the contents of other databases or roles.
"""

import argparse
import base64
import hashlib
import hmac
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
ENV_FILE = BACKEND_DIR / ".env"
ENVIRONMENTS = {
    "dev": ("finpilot_dev", "finpilot_dev_user"),
    "test": ("finpilot_test", "finpilot_test_user"),
}
SCRAM_ITERATIONS = 4096
HOST = "127.0.0.1"


def scram_verifier(password: str, salt: bytes | None = None) -> str:
    """A SCRAM-SHA-256 verifier (RFC 5802, RFC 7677), so plaintext never reaches the server."""
    salt = salt or secrets.token_bytes(16)
    salted = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, SCRAM_ITERATIONS)
    client_key = hmac.digest(salted, b"Client Key", "sha256")
    server_key = hmac.digest(salted, b"Server Key", "sha256")
    stored_key = hashlib.sha256(client_key).digest()
    return f"SCRAM-SHA-256${SCRAM_ITERATIONS}:{_b64(salt)}${_b64(stored_key)}:{_b64(server_key)}"


def _b64(value: bytes) -> str:
    return base64.b64encode(value).decode()


def build_sql(verifiers: dict[str, str]) -> str:
    names = [name for pair in ENVIRONMENTS.values() for name in pair]
    databases = ", ".join(f"'{database}'" for database, _ in ENVIRONMENTS.values())
    roles = ", ".join(f"'{role}'" for _, role in ENVIRONMENTS.values())
    sql = [
        f"-- Creates only: {', '.join(names)}",
        "\\set ON_ERROR_STOP on",
        "",
        "-- 1. Stop before changing anything if a name is already taken.",
        "DO $$ BEGIN",
        f"  IF EXISTS (SELECT 1 FROM pg_database WHERE datname IN ({databases}))",
        f"     OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ({roles})) THEN",
        "    RAISE EXCEPTION 'A FinPilot database or role already exists. Nothing was changed.';",
        "  END IF;",
        "END $$;",
    ]
    for key, (database, role) in ENVIRONMENTS.items():
        sql += [
            "",
            f"-- 2. {key}: a login role with no server-wide privileges.",
            f"CREATE ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION",
            f"  NOBYPASSRLS NOINHERIT CONNECTION LIMIT 20 PASSWORD '{verifiers[key]}';",
            "",
            f"-- 3. {key}: a database it owns. Owners can create tables in its public schema.",
            f"CREATE DATABASE {database} OWNER {role} ENCODING 'UTF8' TEMPLATE template0;",
            "",
            "-- 4. Only the owner may connect to it.",
            f"REVOKE ALL ON DATABASE {database} FROM PUBLIC;",
        ]
    sql += [
        "",
        "-- 5. Report the result. Names and booleans only.",
        "SELECT rolname, rolsuper, rolcreatedb, rolcreaterole, rolreplication, rolbypassrls",
        f"  FROM pg_roles WHERE rolname IN ({roles}) ORDER BY rolname;",
        "SELECT d.datname, pg_get_userbyid(d.datdba) AS owner,",
        "       has_database_privilege('finpilot_dev_user', d.oid, 'CONNECT') AS dev_can_connect,",
        "       has_database_privilege('finpilot_test_user', d.oid, 'CONNECT') AS test_can_connect",
        "  FROM pg_database d WHERE NOT d.datistemplate ORDER BY d.datname;",
    ]
    return "\n".join(sql) + "\n"


def env_contents(passwords: dict[str, str], port: int) -> str:
    def url(key: str) -> str:
        database, role = ENVIRONMENTS[key]
        return f"postgresql+psycopg://{role}:{passwords[key]}@{HOST}:{port}/{database}"

    return (
        "# Generated by scripts/provision_local_db.py. Git ignores this file. Never commit it.\n"
        "APP_ENV=development\n"
        "LOG_LEVEL=INFO\n"
        f"DATABASE_URL={url('dev')}\n"
        f"TEST_DATABASE_URL={url('test')}\n"
    )


def find_psql(explicit: str | None) -> str | None:
    if explicit:
        return explicit
    found = shutil.which("psql")
    if found:
        return found
    candidates = sorted(Path(r"C:\Program Files\PostgreSQL").glob("*/bin/psql.exe"), reverse=True)
    return str(candidates[0]) if candidates else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--print-sql", action="store_true", help="show the SQL and connect to nothing"
    )
    parser.add_argument("--admin-user", default="postgres")
    parser.add_argument("--port", type=int, default=5432)
    parser.add_argument("--psql", help="path to psql, if it isn't found automatically")
    args = parser.parse_args()

    if args.print_sql:
        print(build_sql(dict.fromkeys(ENVIRONMENTS, "<SCRAM verifier generated at run time>")))
        return 0

    if ENV_FILE.exists():
        print(f"{ENV_FILE.name} already exists, so nothing was changed. Move it first if intended.")
        return 2
    psql = find_psql(args.psql)
    if not psql:
        print("psql wasn't found. Pass its location with --psql.")
        return 2

    # URL-safe characters only, so the passwords need no escaping in a database URL.
    passwords = {key: secrets.token_urlsafe(32) for key in ENVIRONMENTS}
    verifiers = {key: scram_verifier(password) for key, password in passwords.items()}

    with tempfile.TemporaryDirectory() as directory:
        script = Path(directory) / "provision.sql"
        script.write_text(build_sql(verifiers), encoding="utf-8")
        command = [
            psql, "-X", "-h", HOST, "-p", str(args.port), "-U", args.admin_user, "-d", "postgres",
            "-f", str(script),
        ]  # fmt: skip
        print(f"psql will ask for the password of '{args.admin_user}'.")
        result = subprocess.run(command, check=False)  # noqa: S603 - a fixed command, no shell

    if result.returncode != 0:
        print(
            "\nProvisioning didn't finish, and backend/.env wasn't written. If it reports that a "
            "name exists, nothing changed. Otherwise, see the psql error above."
        )
        return result.returncode

    ENV_FILE.write_text(env_contents(passwords, args.port), encoding="utf-8", newline="\n")
    print(f"\nDone. Connection settings were written to {ENV_FILE.name}. No secret was printed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
